def _atomic_write_private_json(path: pathlib.Path, value: dict[str, Any]) -> None:
    content = (json.dumps(value, indent=2, sort_keys=True) + "\n").encode("utf-8")
    parent = pathlib.Path(path.parent)
    _validate_install_ancestor_chain(parent)
    parent_fd = _open_or_create_directory_chain(_canonical_install_path(parent))
    temporary_name = f".{path.name}.tmp-{uuid.uuid4().hex}"
    try:
        descriptor = os.open(
            temporary_name,
            os.O_CREAT | os.O_EXCL | os.O_WRONLY | getattr(os, "O_NOFOLLOW", 0),
            0o600,
            dir_fd=parent_fd,
        )
        try:
            offset = 0
            while offset < len(content):
                written = os.write(descriptor, content[offset:])
                if written <= 0:
                    raise OSError("short private JSON write")
                offset += written
            os.fchmod(descriptor, 0o600)
            os.fsync(descriptor)
        finally:
            os.close(descriptor)
        if _entry_exists(parent_fd, path.name):
            metadata = os.stat(path.name, dir_fd=parent_fd, follow_symlinks=False)
            if not stat.S_ISREG(metadata.st_mode):
                raise InstallError(f"managed JSON target must be a regular file: {path}")
        os.replace(
            temporary_name,
            path.name,
            src_dir_fd=parent_fd,
            dst_dir_fd=parent_fd,
        )
        os.fsync(parent_fd)
    finally:
        try:
            os.unlink(temporary_name, dir_fd=parent_fd)
        except FileNotFoundError:
            pass
        os.close(parent_fd)


def _validate_install_state(value: Any) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise InstallError("install state must be an object")
    required = {
        "schema_version",
        "current_version",
        "previous_version",
        "hook_protocol_version",
        "data_schema_version",
        "port",
        "installed_clients",
    }
    optional_python = {"python_executable", "python_version"}
    keys = set(value)
    if not required.issubset(keys) or keys.difference(required | optional_python):
        raise InstallError("install state has an invalid structure")
    present_python_fields = keys & optional_python
    if present_python_fields and present_python_fields != optional_python:
        raise InstallError("install state has an invalid Python structure")
    schema_version = value["schema_version"]
    if (
        isinstance(schema_version, bool)
        or not isinstance(schema_version, int)
        or schema_version != 1
    ):
        raise InstallError("install state schema version is invalid")
    for key in ("hook_protocol_version", "data_schema_version"):
        item = value[key]
        if isinstance(item, bool) or not isinstance(item, int) or item < 1:
            raise InstallError("install state has an invalid structure")
    current_version = value["current_version"]
    if not isinstance(current_version, str) or not _VERSION_PATTERN.fullmatch(current_version):
        raise InstallError("install state has an invalid current version")
    previous_version = value["previous_version"]
    if previous_version is not None and (
        not isinstance(previous_version, str) or not _VERSION_PATTERN.fullmatch(previous_version)
    ):
        raise InstallError("install state has an invalid previous version")
    port = value["port"]
    if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
        raise InstallError("install state has an invalid port")
    clients = value["installed_clients"]
    if (
        not isinstance(clients, list)
        or any(
            not isinstance(client, str) or client not in {"codex", "claude-code"}
            for client in clients
        )
        or len(clients) != len(set(clients))
    ):
        raise InstallError("install state has invalid installed clients")
    if optional_python.issubset(keys):
        executable = value["python_executable"]
        version = value["python_version"]
        if (
            not isinstance(executable, str)
            or not executable
            or not isinstance(version, str)
            or not _PYTHON_VERSION_PATTERN.fullmatch(version)
        ):
            raise InstallError("install state has an invalid Python structure")
    return value


def read_install_state(paths: RuntimePaths) -> dict[str, Any]:
    path = install_state_path(paths)
    try:
        _validate_install_ancestor_chain(path.parent)
        parent_fd = os.open(_canonical_install_path(path.parent), _DIRECTORY_OPEN_FLAGS)
    except FileNotFoundError:
        return {}
    except (OSError, ValueError) as error:
        raise InstallError("install state is unreadable") from error
    try:
        if not _entry_exists(parent_fd, path.name):
            return {}
        raw = _read_regular_file_at(parent_fd, path.name, path)
    except (OSError, ValueError) as error:
        raise InstallError("install state is unreadable") from error
    finally:
        os.close(parent_fd)
    try:
        value = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise InstallError("install state is malformed") from error
    return _validate_install_state(value)


def write_install_state(paths: RuntimePaths, value: dict[str, Any]) -> None:
    _atomic_write_private_json(install_state_path(paths), value)


ManagedCurrentSnapshot = tuple[tuple[int, int], str]
CurrentEntrySnapshot = tuple[tuple[int, int, int], str | None]


def _current_entry_snapshot_at(
    install_fd: int,
    name: str,
) -> CurrentEntrySnapshot | None:
    try:
        metadata = os.stat(name, dir_fd=install_fd, follow_symlinks=False)
    except FileNotFoundError:
        return None
    link = os.readlink(name, dir_fd=install_fd) if stat.S_ISLNK(metadata.st_mode) else None
    return _temporary_identity(metadata), link


def _managed_current_snapshot_at(install_fd: int) -> ManagedCurrentSnapshot | None:
    entry = _current_entry_snapshot_at(install_fd, "current")
    if entry is None:
        return None
    identity, link = entry
    if not stat.S_ISLNK(identity[2]) or link is None:
        raise InstallError("current runtime must be a managed symlink")
    prefix = "releases/"
    if not link.startswith(prefix) or pathlib.PurePosixPath(link).name != link[len(prefix):]:
        raise InstallError("current runtime symlink is not managed")
    return identity[:2], link


def _entry_matches_managed_current(
    entry: CurrentEntrySnapshot | None,
    expected: ManagedCurrentSnapshot,
) -> bool:
    return (
        entry is not None
        and entry[0][:2] == expected[0]
        and stat.S_ISLNK(entry[0][2])
        and entry[1] == expected[1]
    )


def _quarantine_current_entry_at(install_fd: int, name: str) -> str:
    while True:
        quarantine_name = f".current.conflict-{uuid.uuid4().hex}"
        try:
            _darwin_renameat(
                install_fd,
                name,
                install_fd,
                quarantine_name,
                RENAME_EXCL,
            )
            return quarantine_name
        except FileExistsError:
            continue


def _remove_current_entry_exact_at(
    install_fd: int,
    name: str,
    expected: CurrentEntrySnapshot,
) -> None:
    quarantine_name = _quarantine_current_entry_at(install_fd, name)
    claimed = _current_entry_snapshot_at(install_fd, quarantine_name)
    if claimed != expected:
        try:
            _darwin_renameat(
                install_fd,
                quarantine_name,
                install_fd,
                name,
                RENAME_EXCL,
            )
        except OSError:
            pass
        raise InstallError("current runtime changed concurrently during rollback")
    try:
        _unlink_claimed_entry_exact(
            install_fd,
            quarantine_name,
            expected,
            _current_entry_snapshot_at,
            "current",
            pathlib.Path(name),
        )
    except BaseException:
        primary = sys.exc_info()[1]
        cleanup_failures: list[LifecycleCleanupFailure] = []
        try:
            exists = _entry_exists(install_fd, quarantine_name)
        except BaseException as cleanup_error:
            exists = False
            cleanup_failures.append(("current quarantine check", cleanup_error))
        if exists:
            try:
                _restore_claimed_entry(install_fd, quarantine_name, name)
            except BaseException as cleanup_error:
                cleanup_failures.append(("current quarantine restore", cleanup_error))
        if primary is not None and cleanup_failures:
            _attach_lifecycle_cleanup_failures(primary, cleanup_failures)
        raise


def _recover_current_exchange_mismatch(
    install_fd: int,
    temporary_name: str,
    manager_entry: CurrentEntrySnapshot,
) -> NoReturn:
    seen: set[CurrentEntrySnapshot] = set()
    for _ in range(CURRENT_RECOVERY_SWAP_LIMIT):
        observed = _current_entry_snapshot_at(install_fd, temporary_name)
        if observed is None:
            raise InstallError("current runtime changed concurrently during rollback")
        if observed == manager_entry:
            _remove_current_entry_exact_at(install_fd, temporary_name, manager_entry)
            raise InstallError("current runtime changed concurrently during rollback")
        if observed in seen:
            _quarantine_current_entry_at(install_fd, temporary_name)
            raise InstallError("current runtime changed concurrently during rollback")
        seen.add(observed)
        _darwin_renameat(
            install_fd,
            temporary_name,
            install_fd,
            "current",
            RENAME_SWAP,
        )
    _quarantine_current_entry_at(install_fd, temporary_name)
    raise InstallError(
        "current runtime changed concurrently during rollback; "
        "continuous concurrent writes prevented recovery convergence"
    )


def _snapshot_managed_current(paths: RuntimePaths) -> ManagedCurrentSnapshot | None:
    install_root = pathlib.Path(paths.install_root)
    _validate_install_ancestor_chain(install_root)
    try:
        install_fd = os.open(_canonical_install_path(install_root), _DIRECTORY_OPEN_FLAGS)
    except FileNotFoundError:
        return None
    try:
        return _managed_current_snapshot_at(install_fd)
    finally:
        os.close(install_fd)


def _current_version(paths: RuntimePaths) -> str | None:
    snapshot = _snapshot_managed_current(paths)
    return None if snapshot is None else snapshot[1][len("releases/"):]


def _activate_managed_version(
    paths: RuntimePaths,
    version: str,
    *,
    expected_current: ManagedCurrentSnapshot | None | object = _NO_SNAPSHOT_CHECK,
) -> ManagedCurrentSnapshot:
    if not isinstance(version, str) or not _VERSION_PATTERN.fullmatch(version):
        raise InstallError("rollback version must be a semantic version")
    release = pathlib.Path(paths.install_root) / "releases" / version
    if not release.is_dir() or release.is_symlink():
        raise InstallError(f"release is not installed: {version}")
    install_root = pathlib.Path(paths.install_root)
    _validate_install_ancestor_chain(install_root)
    install_fd = _open_or_create_directory_chain(_canonical_install_path(install_root))
    temporary_name = f".current.tmp-{uuid.uuid4().hex}"
    manager_entry: CurrentEntrySnapshot | None = None
    displaced_to_remove: CurrentEntrySnapshot | None = None
    try:
        os.symlink(f"releases/{version}", temporary_name, dir_fd=install_fd)
        manager_entry = _current_entry_snapshot_at(install_fd, temporary_name)
        if manager_entry is None:
            raise InstallError("current runtime temporary disappeared before activation")
        if expected_current is _NO_SNAPSHOT_CHECK:
            os.replace(
                temporary_name,
                "current",
                src_dir_fd=install_fd,
                dst_dir_fd=install_fd,
            )
        elif expected_current is None:
            try:
                _darwin_renameat(
                    install_fd,
                    temporary_name,
                    install_fd,
                    "current",
                    RENAME_EXCL,
                )
            except FileExistsError as error:
                raise InstallError(
                    "current runtime changed concurrently during rollback"
                ) from error
        else:
            _darwin_renameat(
                install_fd,
                temporary_name,
                install_fd,
                "current",
                RENAME_SWAP,
            )
            displaced = _current_entry_snapshot_at(install_fd, temporary_name)
            active = _current_entry_snapshot_at(install_fd, "current")
            if (
                not _entry_matches_managed_current(displaced, expected_current)
                or active != manager_entry
            ):
                _recover_current_exchange_mismatch(
                    install_fd,
                    temporary_name,
                    manager_entry,
                )
            if displaced is None:
                raise InstallError("current runtime disappeared during activation")
            displaced_to_remove = displaced
        committed = _managed_current_snapshot_at(install_fd)
        if committed is None:
            raise InstallError("current runtime disappeared after activation")
        try:
            if displaced_to_remove is not None:
                _remove_current_entry_exact_at(
                    install_fd,
                    temporary_name,
                    displaced_to_remove,
                )
            os.fsync(install_fd)
        except BaseException as error:
            try:
                setattr(error, "_current_commit_snapshot", committed)
            except BaseException:
                pass
            raise
        return committed
    finally:
        primary_error = sys.exc_info()[1]
        cleanup_failures: list[LifecycleCleanupFailure] = []
        try:
            try:
                remaining = _current_entry_snapshot_at(install_fd, temporary_name)
                if manager_entry is not None and remaining == manager_entry:
                    _remove_current_entry_exact_at(
                        install_fd,
                        temporary_name,
                        manager_entry,
                    )
            except BaseException as cleanup_error:
                cleanup_failures.append(("current temporary", cleanup_error))
        finally:
            try:
                os.close(install_fd)
            except BaseException as close_error:
                cleanup_failures.append(("current fd", close_error))
        if cleanup_failures:
            if primary_error is not None:
                _attach_lifecycle_cleanup_failures(
                    primary_error,
                    cleanup_failures,
                )
            else:
                _label, cleanup_error = cleanup_failures[0]
                _attach_lifecycle_cleanup_failures(
                    cleanup_error,
                    cleanup_failures[1:],
                )
                raise cleanup_error


def _restore_managed_current(
    paths: RuntimePaths,
    original: ManagedCurrentSnapshot | None,
    committed: ManagedCurrentSnapshot | None,
) -> None:
    current = _snapshot_managed_current(paths)
    if current == original:
        return
    if committed is None or current != committed:
        raise InstallError("current runtime changed concurrently during rollback")
    if original is not None:
        version = original[1][len("releases/"):]
        _activate_managed_version(
            paths,
            version,
            expected_current=committed,
        )
        return

    install_root = pathlib.Path(paths.install_root)
    _validate_install_ancestor_chain(install_root)
    install_fd = os.open(_canonical_install_path(install_root), _DIRECTORY_OPEN_FLAGS)
    try:
        held_name = _quarantine_current_entry_at(install_fd, "current")
        held = _current_entry_snapshot_at(install_fd, held_name)
        if held is not None and _entry_matches_managed_current(held, committed):
            _remove_current_entry_exact_at(install_fd, held_name, held)
            os.fsync(install_fd)
            return
        try:
            _darwin_renameat(
                install_fd,
                held_name,
                install_fd,
                "current",
                RENAME_EXCL,
            )
        except FileExistsError:
            pass
        raise InstallError("current runtime changed concurrently during rollback")
    finally:
        os.close(install_fd)


